class PreviewSession:
    """Cached author document for one effect root, refreshed on author events."""
    __slots__=('root','edit','signature')

    def __init__(self,root):
        self.root=root
        self.edit=None
        self.signature=None

    def matches(self,root):
        return self.root==root

    def accept(self,edit,signature):
        self.edit=edit
        self.signature=signature


def _session(root):
    key=root.as_pointer()
    session=_sessions.get(key)
    if session is None or not session.matches(root):
        session=PreviewSession(root)
        _sessions[key]=session
    return session

