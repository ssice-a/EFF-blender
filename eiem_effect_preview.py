def _target(edit,identity,path):
    ptr=edit.value(identity,path)
    refs=edit.objects[identity].get('references',[])
    field='$.'+'.'.join(map(str,path))
    # Resolve edited PPtr as well as unchanged original references.
    row=next((r for r in refs if r['fileId']==ptr.get('m_FileID') and r['pathId']==ptr.get('m_PathID')),None)
    if row:return _canonical_identity(edit,row.get('identity'))
    own=edit.objects[identity]['native']['cab'].lower()
    cab=own if ptr.get('m_FileID')==0 else next(((r.get('cab') or '').lower() for o in edit.objects.values()
        if o['native']['cab'].lower()==own for r in o['references'] if r['fileId']==ptr.get('m_FileID') and r.get('cab')),None)
    target=(cab+':'+str(ptr.get('m_PathID'))) if cab and ptr.get('m_PathID') else None
    return _canonical_identity(edit,target)

def _texture_coordinates(nodes,links,texture,settings,slot='',floats=None,colors=None,particle_attributes=False):
    uv_field='_MainUVSet' if slot=='_MainTex' else '_BlendUVSet' if slot=='_BlendTex' else '_MaskUVSet' if slot=='_MaskTex' else slot+'UVSet'
    uv_index=int((floats or {}).get(uv_field,settings.get('m_UVSetIndex',0)))
    if uv_index == 1:
        uv_map=nodes.new('ShaderNodeUVMap');uv_map.uv_map='UV1'
        coordinate=uv_map.outputs['UV']
    elif uv_index == 2:
        # PolarUV is generated by the game shader, not mesh UV2. Its exact
        # formula is not verified, so keep Blender preview textured with UV0.
        uv_map=nodes.new('ShaderNodeUVMap');uv_map.uv_map=''
        uv_map.label='PolarUV (UV0 preview fallback)'
        uv_map['eff_uv_preview_mode']='PolarUV'
        uv_map['eff_uv_preview_note']='Game PolarUV formula is not reproduced; preview uses UV0'
        coordinate=uv_map.outputs['UV']
    elif uv_index == 3:
        tex_coord=nodes.new('ShaderNodeTexCoord');tex_coord.label='ScreenUV preview'
        tex_coord['eff_uv_preview_mode']='ScreenUV'
        coordinate=tex_coord.outputs['Window']
    else:
        uv_map=nodes.new('ShaderNodeUVMap');uv_map.uv_map=''
        coordinate=uv_map.outputs['UV']
    if particle_attributes:
        scale_attr=nodes.new('ShaderNodeAttribute');scale_attr.attribute_type='INSTANCER';scale_attr.attribute_name=particle_geometry.UV_SCALE
        offset_attr=nodes.new('ShaderNodeAttribute');offset_attr.attribute_type='INSTANCER';offset_attr.attribute_name=particle_geometry.UV_OFFSET
        per_scale=nodes.new('ShaderNodeVectorMath');per_scale.operation='MULTIPLY'
        links.new(coordinate,per_scale.inputs[0]);links.new(scale_attr.outputs['Vector'],per_scale.inputs[1])
        per_offset=nodes.new('ShaderNodeVectorMath');per_offset.operation='ADD'
        links.new(per_scale.outputs['Vector'],per_offset.inputs[0]);links.new(offset_attr.outputs['Vector'],per_offset.inputs[1])
        coordinate=per_offset.outputs['Vector']
    # Native UV order: source/atlas -> time scroll -> rotate about .5 -> ST.
    scroll=nodes.new('ShaderNodeVectorMath');scroll.operation='ADD';scroll['eff_uv_scroll']=slot
    links.new(coordinate,scroll.inputs[0]);scroll.inputs[1].default_value=(0,0,0)
    coordinate=scroll.outputs['Vector']
    rotate=(colors or {}).get(slot+'UVRotateMat',{})
    if any(abs(rotate.get(k,1 if k in ('r','a') else 0)- (1 if k in ('r','a') else 0))>1e-6 for k in 'rgba'):
        separate=nodes.new('ShaderNodeSeparateXYZ');links.new(coordinate,separate.inputs['Vector'])
        x=_math(nodes,links,'SUBTRACT',separate.outputs['X'],.5);y=_math(nodes,links,'SUBTRACT',separate.outputs['Y'],.5)
        xx=_math(nodes,links,'MULTIPLY',x,rotate.get('r',1));xy=_math(nodes,links,'MULTIPLY',y,rotate.get('b',0))
        yx=_math(nodes,links,'MULTIPLY',x,rotate.get('g',0));yy=_math(nodes,links,'MULTIPLY',y,rotate.get('a',1))
        rx=_math(nodes,links,'ADD',xx,xy);ry=_math(nodes,links,'ADD',yx,yy)
        rx=_math(nodes,links,'ADD',rx,.5);ry=_math(nodes,links,'ADD',ry,.5)
        combine=nodes.new('ShaderNodeCombineXYZ');links.new(rx,combine.inputs['X']);links.new(ry,combine.inputs['Y']);links.new(separate.outputs['Z'],combine.inputs['Z'])
        coordinate=combine.outputs['Vector']
    mapping=nodes.new('ShaderNodeVectorMath');mapping.operation='MULTIPLY_ADD';mapping['eff_uv_slot']=slot
    scale=settings.get('m_Scale',{});offset=settings.get('m_Offset',{})
    links.new(coordinate,mapping.inputs[0]);mapping.inputs[1].default_value=(scale.get('x',1),scale.get('y',1),1);mapping.inputs[2].default_value=(offset.get('x',0),offset.get('y',0),0)
    links.new(mapping.outputs['Vector'],texture.inputs['Vector'])

def _set_input(socket,value):
    current=socket.default_value
    a=(current,) if isinstance(current,(float,int)) else tuple(current)
    b=(value,) if isinstance(value,(float,int)) else tuple(value)
    if len(a)!=len(b) or any(not math.isclose(x,y,rel_tol=1e-6,abs_tol=1e-7) for x,y in zip(a,b)):
        socket.default_value=value


def _material_values(mat,edit,mid):
    if not mat.use_nodes or mid not in edit.state['values']:return
    fields=edit.value(mid).get('m_SavedProperties',{})
    floats={r['first']:r['second'] for r in fields.get('m_Floats',[])}
    colors={r['first']:r['second'] for r in fields.get('m_Colors',[])}
    textures={r['first']:r['second'] for r in fields.get('m_TexEnvs',[])}
    scene=bpy.context.scene;time=(scene.frame_current+scene.frame_subframe-scene.frame_start)/(scene.render.fps/scene.render.fps_base)
    nodes=mat.node_tree.nodes
    for node in nodes:
        slot=node.get('eff_uv_slot')
        if slot and slot in textures:
            settings=textures[slot];scale=settings.get('m_Scale',{});offset=settings.get('m_Offset',{})
            _set_input(node.inputs[1],(scale.get('x',1),scale.get('y',1),1))
            _set_input(node.inputs[2],(offset.get('x',0),offset.get('y',0),0))
        scroll=node.get('eff_uv_scroll')
        if scroll:
            speed=colors.get(scroll+'UVSpeed',{})
            _set_input(node.inputs[1],(speed.get('r',0)*time,speed.get('g',0)*time,0))
    tint=colors.get('_TintColor',colors.get('_BaseColor',colors.get('_Color',dict(r=1,g=1,b=1,a=1))))
    if nodes.get('EFF Tint'):_set_input(nodes['EFF Tint'].inputs[2],tuple(tint.get(k,1) for k in 'rgba'))
    if nodes.get('EFF Alpha'):_set_input(nodes['EFF Alpha'].inputs[1],tint.get('a',1)*floats.get('_TintColorAlpha',1)*floats.get('_ProcedureAlpha',1))
    if nodes.get('EFF Shader'):_set_input(nodes['EFF Shader'].inputs['Emission Strength'],floats.get('_TintColorIntensity',1)*floats.get('_ExpIntensity',1))
    if nodes.get('EFF Dissolve'):_set_input(nodes['EFF Dissolve'].inputs[1],floats.get('_DissolveScheduleOffset',0))


def _math(nodes,links,operation,a,b=None,name=''):
    node=nodes.new('ShaderNodeMath');node.operation=operation
    if name:node.name=name
    if isinstance(a,bpy.types.NodeSocket):links.new(a,node.inputs[0])
    else:node.inputs[0].default_value=a
    if b is not None:
        if isinstance(b,bpy.types.NodeSocket):links.new(b,node.inputs[1])
        else:node.inputs[1].default_value=b
    return node.outputs[0]


def _multiply_rgb(nodes,links,left,right,name=''):
    node=nodes.new('ShaderNodeMixRGB');node.blend_type='MULTIPLY';node.inputs[0].default_value=1
    if name:node.name=name
    links.new(left,node.inputs[1])
    if isinstance(right,bpy.types.NodeSocket):links.new(right,node.inputs[2])
    else:node.inputs[2].default_value=right
    return node.outputs[0]


def _sample_texture(root,edit,mid,index,row,resources,nodes,links,floats,colors,particle_attributes):
    try:image=assets.image_for_slot(root,edit,mid,index,resources)
    except (KeyError,ValueError,StopIteration):return None
    if image is None:return None
    tex=nodes.new('ShaderNodeTexImage');tex.image=image;tex.label=row['first']
    _texture_coordinates(nodes,links,tex,row['second'],row['first'],floats,colors,particle_attributes)
    return tex


def _layout_material_nodes(tree):
    """Place generated preview nodes in deterministic left-to-right layers.

    The preview graph is generated from native texture and shader fields, so
    Blender gives every new node the default position (0, 0).  Layout follows
    the actual links instead of guessing shader semantics: source nodes stay on
    the left, processing branches occupy intermediate columns, and the shader
    output ends on the right.  Only ``Node.location`` changes; links and values
    are deliberately untouched.
    """
    nodes = list(tree.nodes)
    if not nodes:
        return
    incoming = {id(node): [] for node in nodes}
    outgoing = {id(node): [] for node in nodes}
    for link in tree.links:
        source, target = link.from_node, link.to_node
        if id(source) not in outgoing or id(target) not in incoming:
            continue
        outgoing[id(source)].append(target)
        incoming[id(target)].append(source)

    # Rank nodes by the longest source-to-node path.  The small fixed-point
    # loop also handles an accidental cycle without hanging the UI.
    ranks = {id(node): 0 for node in nodes}
    for _ in range(len(nodes)):
        changed = False
        for node in nodes:
            parents = incoming[id(node)]
            if not parents:
                continue
            rank = 1 + max(ranks[id(parent)] for parent in parents)
            if rank != ranks[id(node)]:
                ranks[id(node)] = rank
                changed = True
        if not changed:
            break

    def sort_key(node):
        # Keep the common graph readable within a column while remaining
        # deterministic for localized node names.
        type_order = {
            'VERTEX_COLOR': 0, 'ATTRIBUTE': 1, 'UVMAP': 2,
            'VECT_MATH': 3, 'TEX_IMAGE': 4, 'SEPARATE_COLOR': 5,
            'MATH': 6, 'MIX_RGB': 7, 'NORMAL_MAP': 8,
            'BSDF_PRINCIPLED': 9, 'OUTPUT_MATERIAL': 10,
        }
        return (type_order.get(node.type, 20), node.label or node.name)

    by_rank = {}
    for node in nodes:
        by_rank.setdefault(ranks[id(node)], []).append(node)
    columns = sorted(by_rank)
    column_x = {}
    x = 0.0
    for rank in columns:
        column_x[rank] = x
        x += max((float(node.width) for node in by_rank[rank]), default=180.0) + 100.0

    def node_height(node):
        visible_sockets = sum(not socket.hide for socket in list(node.inputs) + list(node.outputs))
        estimated = 58.0 + visible_sockets * 20.0
        return max(float(node.height), float(node.dimensions.y), estimated, 90.0)

    for rank, column in by_rank.items():
        column.sort(key=sort_key)
        top = 0.0
        for node in column:
            node.location = (column_x[rank], top)
            top -= node_height(node) + 44.0


def _ensure_material_node_layout(mat):
    if not mat or not mat.use_nodes or mat.get('eff_preview_node_layout') == 'v1':
        return
    _layout_material_nodes(mat.node_tree)
    mat['eff_preview_node_layout'] = 'v1'


