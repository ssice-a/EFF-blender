def sync_visibility(root):
    """Gate generated previews without resampling particles or native fields.

    hide_viewport retains native/config visibility; the per-view-layer eye is
    only the author hierarchy gate. Particle templates are never registered.
    """
    entry=_visibility_previews.get(root.as_pointer())
    if not entry:return
    layer=bpy.context.view_layer
    if not layer:return
    cache={}
    for key,obj in list(entry[1].items()):
        try:
            if layer.objects.get(obj.name)!=obj:continue
            if not obj.parent:
                entry[1].pop(key,None)
                continue
            hidden=not _view_visible(obj.parent,layer,cache)
            if obj.hide_get(view_layer=layer)!=hidden:obj.hide_set(hidden,view_layer=layer)
        except ReferenceError:
            entry[1].pop(key,None)


def visibility_update():
    global _visibility_scan
    if not _sync:return None
    if not _busy:
        # load/undo clears cached Object references. Reindex existing previews
        # once; ordinary idle ticks never traverse the scene or native data.
        if _visibility_scan:
            scene=bpy.context.scene
            if scene:
                for obj in scene.objects:
                    if obj.get('eff_preview_key') and obj.parent:
                        root=_root_of(obj.parent) if _root_of else None
                        if root:_track_visibility(root,obj)
            _visibility_scan=False
        for key,(root,_) in list(_visibility_previews.items()):
            try:sync_visibility(root)
            except ReferenceError:_visibility_previews.pop(key,None)
    return POLL_INTERVAL

